import { randomBytes } from "node:crypto";
import type { ProjectRecord } from "./types.js";

/**
 * What ThreadSite projects are called and identified by, in one place: the
 * bot-created placeholder identity, published/repo/relay/credential name
 * rules, Forgejo ownership markers, publish leftovers, and the relay game id.
 * Removal, purge and inventory read the same definitions that creation and
 * rename write, so the two can never drift apart.
 */

// Bot-created threads start as "site-<slug>"/"game-<slug>" until automatic
// naming adopts the agent's choice; every consumer of that convention shares
// this predicate.
export const BOT_CREATED_IDENTITY = /^(?:site|game)-/i;

export function isBotCreatedIdentity(value: string): boolean {
  return BOT_CREATED_IDENTITY.test(value);
}

/** Bot-created slugs only: strip one or more stacked "site-"/"game-" prefixes. */
export function stripBotCreatedSlug(value: string): string {
  return value.replace(/^(?:(?:site|game)-)+/, "");
}

// Temporary repositories are created as "site-<siteSlug>" until the durable
// naming pass renames the repository to the bare slug.
export function temporaryRepoName(siteSlug: string): string {
  return `site-${siteSlug}`.slice(0, 80);
}

/** Published site directories and gallery slugs (the site slug itself). */
export const SLUG_PATTERN = /^[a-z0-9][a-z0-9-]{0,79}$/;

/** Relay tenant keys. bot/networking and gameserver keep compiled copies of this rule; parity tests assert equality. */
export const GAME_ID_PATTERN = /^[a-z0-9][a-z0-9-]{2,63}$/;

/** Forgejo repository names the harness creates and inventories. */
export const REPO_NAME_PATTERN = /^[a-zA-Z0-9][a-zA-Z0-9_.-]{0,99}$/;

/** Push-key accounts the credential generator creates (`push-` + 6 unambiguous characters). */
export const PUSH_ACCOUNT_PATTERN = /^push-[a-z0-9]{6}$/;

/** Record-level validation of stored account names; broader than the generator in case older shapes exist. */
export const PUSH_ACCOUNT_RECORD_PATTERN = /^push-[a-zA-Z0-9_-]+$/;

// Unambiguous alphabet for generated push credentials: no 0/O/1/l/I.
const CREDENTIAL_ALPHABET = "abcdefghjkmnpqrstuvwxyz23456789";

function randomCredential(length: number): string {
  const bytes = randomBytes(length);
  let out = "";
  for (let i = 0; i < length; i++) out += CREDENTIAL_ALPHABET[bytes[i]! % CREDENTIAL_ALPHABET.length];
  return out;
}

/**
 * Username/password pair for a repo push-key account. Random on every call;
 * persistence is the caller's job (the project record).
 */
export function generatePushCredentials(): { username: string; password: string } {
  return { username: `push-${randomCredential(6)}`, password: randomCredential(20) };
}

/** The repository description the harness writes, and the shapes it recognizes as its own. */
export function managedRepoDescription(kindLabel: string): string {
  return `${kindLabel} generated by ThreadSite`;
}

export function isManagedRepoDescription(description: string | undefined): boolean {
  return /^(?:static website|[23]D static web game) generated (?:from Discord thread .+|by ThreadSite)$/i.test(description ?? "");
}

// README.md's harness header carries this sentence; Forgejo-side ownership
// checks match on it, so the writer and the matcher must use one constant.
// The Discord-harness variant exists only for repositories created before the
// wording settled; nothing still writes it.
export const README_OWNERSHIP_MARKER = "maintained by the ThreadSite harness.";
export const README_OWNERSHIP_MARKERS = [README_OWNERSHIP_MARKER, "maintained by the ThreadSite Discord harness."];

/** Harness-owned gallery assets at the publish root; the leading underscores keep cleanup from reading them as site slugs. */
export const GALLERY_DIR = "__gallery";

// Atomic publication stages into ".staging-<slug>-<suffix>" and moves the old
// tree aside as ".backup-<slug>-<suffix>"; crash recovery and orphan purge
// recognize exactly this shape.
export function publishLeftoverSuffix(): string {
  return randomBytes(5).toString("hex");
}

export const PUBLISH_LEFTOVER_PATTERN = /^\.(staging|backup)-(.+)-[0-9a-f]{10}$/;

/** Whether a publish-root entry is a staging/backup leftover of exactly this slug (no prefix matches). */
export function isPublishLeftoverOf(name: string, slug: string): boolean {
  return new RegExp(`^\\.(?:staging|backup)-${slug}-[a-f0-9]{10}$`).test(name);
}

/** The site slug a staging/backup leftover belongs to, or undefined for a plain published slug. */
export function publishLeftoverSlug(name: string): string | undefined {
  return PUBLISH_LEFTOVER_PATTERN.exec(name)?.[2];
}

/** Git commit references are stored and compared as this many leading hash characters. */
export const COMMIT_SHORT_HASH_CHARS = 10;

/**
 * The project's relay tenant id, if it has one: the durable multiplayerGameId
 * once assigned, or the site slug for a game that has never been renamed.
 * Every game kind carries relay data under this id (leaderboard scores for all
 * modes; worlds and rooms for arena/rooms), so deletion, rename, exclusivity
 * checks and orphan purge all resolve it the same way.
 */
export function relayTenantId(project: ProjectRecord): string | undefined {
  return project.multiplayerGameId ?? (project.projectKind?.startsWith("game-") ? project.siteSlug : undefined);
}
